#!/bin/bash
# Regenerates shaders_spv.h from the GLSL sources with the NDK's glslc
# (ndk/<version>/shader-tools/<host>/glslc), e.g.  GLSLC=/path/to/glslc ./build.sh
set -e
cd "$(dirname "$0")"
GLSLC=${GLSLC:-glslc}
out=../shaders_spv.h
tmp=$(mktemp -d)
{
  echo "// Generated by shaders/build.sh. Do not edit."
  echo "#pragma once"
  echo "#include <cstdint>"
  for s in fullscreen.vert planar_csc.frag ycc_pack.frag sgsr_flow.comp sgsr_spatial.comp sgsr_activate.comp sgsr_upscale.comp sgsr_present.frag sgsr_pack.frag; do
    name=$(echo "$s" | tr '.' '_')
    "$GLSLC" -O --target-env=vulkan1.1 "$s" -o "$tmp/$name.spv"
    echo "static const uint32_t ${name}_spv[] = {"
    od -An -v -t x4 -w16 "$tmp/$name.spv" | sed 's/ \([0-9a-f]\{8\}\)/ 0x\1,/g'
    echo "};"
  done
} > "$out"
rm -rf "$tmp"
