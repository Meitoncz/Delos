package com.limelight.utils

import java.io.BufferedReader
import java.io.IOException
import java.io.Reader

/**
 * The `.art` file: a text file that starts one game of a paired PC when it is opened (ES-DE and other
 * frontends hand it to ShortcutTrampoline, which reads it with [parseArtFile]). One `[key] value` per line;
 * lines starting with `#` and blank lines are comments.
 */
const val ART_KEY_HOST_UUID = "host_uuid"
const val ART_KEY_HOST_NAME = "host_name"
const val ART_KEY_APP_UUID = "app_uuid"
const val ART_KEY_APP_NAME = "app_name"
const val ART_KEY_APP_ID = "app_id"

/** What the `.art` file names; every value is null when the file does not have the key. */
data class ArtEntry(
    val hostUuid: String?,
    val hostName: String?,
    val appUuid: String?,
    val appName: String?,
    val appId: String?,
)

/**
 * Reads a `.art` file. A line that is neither a comment nor blank must be a `[key] value` pair; a line
 * without a value is skipped, any other line makes the whole file invalid ([IOException]).
 */
@Throws(IOException::class)
fun parseArtFile(reader: Reader): ArtEntry {
    val data = HashMap<String, String>()
    val lines = if (reader is BufferedReader) reader else BufferedReader(reader)
    while (true) {
        var line = lines.readLine() ?: break
        line = line.trim()
        if (line.startsWith("#") || line.isEmpty()) continue // Skip comments and empty lines
        if (!line.startsWith("[")) throw IOException("Invalid .art file format")

        val separator = line.indexOf(' ')
        if (separator > 0 && separator < line.length - 1) {
            val key = line.substring(0, separator).trim()
            val value = line.substring(separator + 1).trim()
            if (!key.endsWith("]")) throw IOException("Invalid .art file format")
            data[key.substring(1, key.length - 1)] = value
        }
    }
    return ArtEntry(data[ART_KEY_HOST_UUID], data[ART_KEY_HOST_NAME], data[ART_KEY_APP_UUID], data[ART_KEY_APP_NAME], data[ART_KEY_APP_ID])
}

/** One line of text: every run of line breaks and control characters becomes one space, so a value cannot add keys. */
private fun oneLine(value: String): String {
    val out = StringBuilder(value.length)
    var gap = false
    value.forEach { c ->
        if (Character.isISOControl(c) || c == '\u2028' || c == '\u2029') {
            gap = true
        } else {
            if (gap) out.append(' ')
            gap = false
            out.append(c)
        }
    }
    return out.toString().trim()
}

/**
 * The content of the `.art` file of one game, as [parseArtFile] reads it back (names are written as one
 * line, trimmed). The PC and the game are named by their UUIDs; the game's numeric id is written only for
 * a game without a UUID (older servers), because the UUID takes precedence when both are there.
 */
fun artFileContent(pcUuid: String, pcName: String, appUuid: String?, appName: String, appId: Int): String {
    val hostUuid = oneLine(pcUuid)
    require(hostUuid.isNotEmpty()) { "A .art file needs the PC's UUID" }
    val gameUuid = appUuid?.let(::oneLine).orEmpty()
    val gameName = oneLine(appName)
    require(gameUuid.isNotEmpty() || gameName.isNotEmpty() || appId > 0) { "A .art file needs the game's UUID, name or id" }

    return buildString {
        append("# Delos app entry\n")
        append("# Generated by Delos for Android\n\n")
        fun entry(key: String, value: String) {
            if (value.isNotEmpty()) append('[').append(key).append("] ").append(value).append('\n')
        }
        entry(ART_KEY_HOST_UUID, hostUuid)
        entry(ART_KEY_HOST_NAME, oneLine(pcName))
        entry(ART_KEY_APP_UUID, gameUuid)
        entry(ART_KEY_APP_NAME, gameName)
        if (gameUuid.isEmpty() && appId > 0) entry(ART_KEY_APP_ID, appId.toString())
    }
}

/** Longest game name used in a file name (in characters), so the name stays well inside file system limits. */
const val ART_FILE_NAME_MAX = 120

private const val ART_FILE_FALLBACK = "Delos game"

/**
 * The file name (with the `.art` extension) of a game's shortcut: the name with what file names and
 * Storage Access Framework display names cannot hold (`/ \ : * ? " < > |` and control characters) turned
 * into spaces, spaces and dots trimmed from both ends, kept at [ART_FILE_NAME_MAX] characters. Other
 * characters, Unicode included, stay.
 */
fun artFileName(appName: String): String {
    val out = StringBuilder(appName.length)
    var space = false
    appName.forEach { c ->
        val blank = c in "/\\:*?\"<>|" || Character.isISOControl(c) || Character.isWhitespace(c) || c == '\u00A0' || c == '\u2028' || c == '\u2029'
        if (blank) {
            space = true
        } else {
            if (space && out.isNotEmpty()) out.append(' ')
            space = false
            out.append(c)
        }
    }
    var base = out.toString().trim(' ', '.')
    if (base.codePointCount(0, base.length) > ART_FILE_NAME_MAX) {
        base = base.substring(0, base.offsetByCodePoints(0, ART_FILE_NAME_MAX)).trim(' ', '.')
    }
    return (base.ifEmpty { ART_FILE_FALLBACK }) + ".art"
}
